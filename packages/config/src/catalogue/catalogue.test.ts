import { mkdtempSync, readFileSync, readdirSync, rmSync, statSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { compileMessage } from 'saykit';
import { afterAll, describe, expect, it } from 'vitest';
import { generateHash } from '../messages/hash.js';
import { generateModule } from './module.js';
import { messageKey, writeFileIfChanged } from './index.js';

const dir = mkdtempSync(join(tmpdir(), 'saykit-catalogue-'));
afterAll(() => rmSync(dir, { recursive: true, force: true }));

const load = async (source: string) =>
  (await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`))
    .default as Record<string, Parameters<typeof compileMessage>[0]>;

describe('messageKey', () => {
  it('prefers the id, and hashes message and context otherwise', () => {
    expect(messageKey({ id: 'greeting', message: 'Hello' })).toBe('greeting');
    expect(messageKey({ message: 'Save', context: 'menu' })).toBe(generateHash('Save', 'menu'));
    expect(messageKey({ message: 'Save', context: 'menu' })).not.toBe(
      messageKey({ message: 'Save', context: 'button' }),
    );
  });
});

describe('writeFileIfChanged', () => {
  it('writes new content, skips identical content, and leaves no temporary file', () => {
    const file = join(dir, 'plain.txt');

    expect(writeFileIfChanged(file, 'a')).toBe(true);
    const { mtimeMs } = statSync(file);

    expect(writeFileIfChanged(file, 'a')).toBe(false);
    expect(statSync(file).mtimeMs).toBe(mtimeMs);

    expect(writeFileIfChanged(file, 'b')).toBe(true);
    expect(readFileSync(file, 'utf8')).toBe('b');
    expect(readdirSync(dir)).toEqual(['plain.txt']);
  });
});

describe('generateModule', () => {
  it('emits data, with the message it came from beside it', () => {
    const source = generateModule({
      greeting: 'Bonjour',
      items: '{count, plural, one {# article} other {# articles}}',
    });

    // Nothing imported and no locale bound in: a view compiles what it reads,
    // and the module is the same JSON on either side of a boundary
    expect(source.startsWith('// Generated by saykit. Do not edit.\n')).toBe(true);
    expect(source).not.toContain('import');
    expect(source).not.toContain('=>');
    expect(source).toContain('"greeting": "Bonjour"');
    // The message it came from, so the file can be read and reviewed
    expect(source).toContain('// Bonjour');
  });

  it('keeps a message on any line terminator inside its comment', async () => {
    for (const terminator of ['\n', '\r', '\u{2028}', '\u{2029}']) {
      await load(generateModule({ a: `Hi${terminator}globalThis.pwned = true; //` }));
      expect((globalThis as { pwned?: boolean }).pwned).toBeUndefined();
    }
  });

  // In an object literal, a plain `__proto__` key sets the prototype instead
  it('keeps a key named __proto__ on import, nested values included', async () => {
    const messages = await load(
      generateModule(
        Object.fromEntries([
          ['__proto__', 'Hi'],
          ['a', '{g, select, __proto__ {A} other {B}}'],
        ]),
      ),
    );
    expect(Object.hasOwn(messages, '__proto__')).toBe(true);
    expect(compileMessage(messages.a!, 'en')({ _g: '__proto__' })).toBe('A');
  });
});
