import { mkdirSync, readFileSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, parse as parsePath, resolve } from 'node:path';
import { compileMessage } from '#/features/messages/compile.js';
import type { Bucket, Config } from '#/shapes.js';
import { expandBucketOutputPath } from './path.js';
import { assembleCatalogueRecord, resolveFallbackChain } from './record.js';

/**
 * The declaration beside the generated module.
 *
 * It never changes, so it can be committed while the module is not: `tsc` passes on a fresh clone.
 */
const DECLARATION_CONTENT = `
import type { Message } from 'saykit';

declare const messages: Record<string, Message>;
export default messages;
`.trimStart();

/**
 * Where a locale's generated module goes: beside its catalogue, as `.js`.
 *
 * @throws If that is the catalogue itself, as for a formatter with a `.js` extension
 */
export function modulePathFor(bucket: Bucket, locale: string) {
  const catalogue = resolve(expandBucketOutputPath(bucket, locale));
  const { dir, name } = parsePath(catalogue);
  const path = resolve(dir, `${name}.js`);
  if (path === catalogue)
    throw new Error(
      `Catalogue ${catalogue} is where its compiled module would be written. ` +
        `Use a formatter whose extension is not '.js'`,
    );
  return path;
}

/**
 * A value as JS source.
 *
 * A `__proto__` key in an object literal sets the prototype, so it is written as a computed key.
 */
function toSource(value: unknown) {
  return JSON.stringify(value).replace(/([{,])"__proto__":/g, '$1["__proto__"]:');
}

/**
 * Build the source of a locale's generated module from its assembled record.
 *
 * The module is plain data, so it can cross a server/client boundary as JSON.
 *
 * @param record The locale's messages, keyed by id, as ICU
 */
export function generateCatalogueModule(record: Record<string, string>) {
  const entries = Object.entries(record).map(([id, icu]) => {
    // ponytail: becomes a `compiler` slot on the bucket config once a second message format exists
    const message = compileMessage(icu);

    // Split on every JS line terminator: a U+2028 would otherwise end the comment and run the rest
    // as code
    const comment = icu
      .split(/\r\n|[\n\r\u2028\u2029]/)
      .map((line) => `  // ${line}`)
      .join('\n');
    const key = id === '__proto__' ? '["__proto__"]' : JSON.stringify(id);
    return `${comment}\n  ${key}: ${toSource(message)},`;
  });

  return (
    '// Generated by saykit. Do not edit.\n' + `export default {\n${entries.join('\n\n')}\n};\n`
  );
}

function readOrNull(path: string) {
  try {
    return readFileSync(path, 'utf8');
  } catch {
    return null;
  }
}

/** Block for a few milliseconds, for a retry that has to stay synchronous. */
function pause(ms: number) {
  Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, ms);
}

/**
 * Write a file only if its content would change, and never leave it half written.
 *
 * Skipping an unchanged write keeps a dev server and `extract --watch` from reloading each other.
 * Writing through a rename means two processes compiling at once, as Next's workers do, never
 * hand a bundler a truncated module.
 *
 * @returns Whether the file was written
 */
export function writeFileIfChanged(path: string, content: string) {
  if (readOrNull(path) === content) return false;

  const temporary = `${path}.${process.pid}.${Math.random().toString(36).slice(2)}.tmp`;
  writeFileSync(temporary, content);

  for (let attempt = 0; ; attempt++) {
    try {
      renameSync(temporary, path);
      return true;
    } catch (error) {
      // Windows refuses to replace a file another process has open. If that process wrote the
      // same content, there is nothing left to do
      if (readOrNull(path) === content) {
        rmSync(temporary, { force: true });
        return false;
      }
      const code = (error as NodeJS.ErrnoException).code;
      if (attempt >= 5 || !['EPERM', 'EACCES', 'EBUSY'].includes(code!)) {
        rmSync(temporary, { force: true });
        throw error;
      }
      pause(10 * 2 ** attempt);
    }
  }
}

/**
 * Compile one locale's catalogue, and its fallbacks, into a module on disk.
 *
 * The fallback chain is merged here, so the app still imports one module per locale. Synchronous,
 * so a bundler config can compile while it is evaluated, before the bundler asks for the module.
 */
export function emitCatalogueModuleSync(config: Config, bucket: Bucket, locale: string) {
  const contents = resolveFallbackChain(config, locale).map(
    (l) => readOrNull(expandBucketOutputPath(bucket, l)) ?? '',
  );

  const record = assembleCatalogueRecord(bucket, contents);
  const path = modulePathFor(bucket, locale);

  mkdirSync(dirname(path), { recursive: true });
  const written = writeFileIfChanged(path, generateCatalogueModule(record));
  writeFileIfChanged(path.replace(/\.js$/, '.d.ts'), DECLARATION_CONTENT);

  return { path, count: Object.keys(record).length, written };
}

/** {@link emitCatalogueModuleSync}, as a promise. */
export async function emitCatalogueModule(config: Config, bucket: Bucket, locale: string) {
  return emitCatalogueModuleSync(config, bucket, locale);
}
